def predicts(rule: str) -> tuple[str | None, str] | None:
    """(יחידה או None, מה/למה) לכלל, או ``None`` -- כלל שאינו רשום (כלל חדש בלי החלטה אם הוא חוזה)."""
    return PREDICTS.get(rule)


def _number(value: object) -> float | None:
    return float(value) if isinstance(value, (int, float)) and not isinstance(value, bool) and value > 0 else None


def judge(rule: str, predicted: object, actual: object) -> bool | None:
    """``True`` = התאים, ``False`` = לא התאים, ``None`` = לא נמדד: לכלל אין הגדרת התאמה, או שאחד המספרים חסר
    או אינו חיובי. אי אפשר ללמוד על התאמה מ"לא ידוע"."""
    tolerance, want, got = TOLERANCE.get(rule), _number(predicted), _number(actual)
    if tolerance is None or want is None or got is None:
        return None
    return abs(got - want) <= tolerance * want
