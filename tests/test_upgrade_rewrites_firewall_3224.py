"""#3224: a server upgraded from a version without `known_macs` gets its firewall rewritten.

The upgrade keeps `/etc/nftables.conf`; #3223 added the `known_macs` set and the rule
`ether saddr @known_macs` for the udpcast ports. Without a rewrite the upgraded server
kept those ports open to every machine on the deploy NIC (#2485 not closed there), and
`known_fw.apply` failed on every boot.

Three layers, each tested from its own side:

1. ``deploy_net.stale_firewall`` -- is the installed conf one that predates the set?
   (no ImageSrv firewall = nothing to do, never enabled by an upgrade, #2440; unreadable
   is a reason, not "fine", principle 5.)
2. server start (``create_runtime``) -- a stale conf runs the same `firewall` step the
   console runs on a NIC change (nft -c, then load, then rollback on failure, #1121),
   *before* the list of registered machines is loaded; a conf that is current is untouched.
3. ``tools/server-upgrade.sh`` -- positive evidence after the new server is live: the
   declaration in the file and the set in the live ruleset. Anything else (no declaration,
   unreadable conf, no live set) rolls back to the previous tag, by name.

Negative control: see the PR body -- every production file the change touched was reverted.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from native import requires_native
from test_installer_1131 import BASH, _status, _upgrade_env, calls, fake_tool, posix, run_bash
from test_server_upgrade_1193 import _success_tools
from test_server_upgrade_1301 import _setup

from server.net import deploy_net

REPO = Path(__file__).resolve().parent.parent
FIXTURES = REPO / "tests" / "fixtures" / "nftables"

# What the installer wrote before #3223: ImageSrv's table, no set, no include.
LEGACY = (
    "#!/usr/sbin/nft -f\n"
    "# ImageSrv -- generated by deploy/nftables-rules.sh. Do not edit.\n"
    "flush ruleset\n"
    "table inet imagesrv {\n"
    "\tchain input {\n"
    "\t\ttype filter hook input priority filter; policy drop;\n"
    '\t\tiifname "ens19" udp dport 9000-9001 accept\n'   # פורט-הפצה-מכוון: the old installed rules, as #3223 found them
    "\t}\n"
    "}\n"
)


def _conf(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "nftables.conf"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


# -- 1. is the installed conf stale? -------------------------------------------------------

@pytest.mark.parametrize("name", ["primary.conf", "secondary.conf", "mcast-custom.conf"])
def test_what_the_generator_writes_today_is_not_stale(name):
    """The marker the check looks for is what the generator really writes (all three snapshots)."""
    text = (FIXTURES / name).read_text(encoding="utf-8")
    assert deploy_net.KNOWN_MACS_DECL in text
    assert deploy_net.stale_firewall(FIXTURES / name) is None


def test_a_conf_from_before_the_set_is_stale_and_says_why(tmp_path):
    reason = deploy_net.stale_firewall(_conf(tmp_path, LEGACY))
    assert reason and "known_macs" in reason and "udpcast" in reason


def test_no_imagesrv_firewall_is_nothing_to_rewrite(tmp_path):
    """#2440: `--no-firewall` stays as the operator left it -- an upgrade never writes one."""
    assert deploy_net.stale_firewall(tmp_path / "absent.conf") is None
    assert deploy_net.stale_firewall(_conf(tmp_path, "table inet filter { }\n")) is None


def test_a_conf_that_cannot_be_read_is_not_a_conf_that_is_fine(tmp_path):
    """Principle 5: a directory where the file should be is an OSError -- a reason, not None."""
    (tmp_path / "nftables.conf").mkdir()
    reason = deploy_net.stale_firewall(tmp_path / "nftables.conf")
    assert reason and "לא ניתן לקרוא" in reason


# -- 2. server start -----------------------------------------------------------------------

def _runtime(tmp_path, images_root, *, stale, fw_step, loaded):
    from test_sender import Recorder                                      # noqa: PLC0415
    from server.app import create_runtime                                 # noqa: PLC0415

    return create_runtime(
        tmp_path / "data", images_root, "http://10.44.12.10:8080",
        sender_runner=Recorder(block=True), wol_send=lambda _p: None,
        nic_hooks={"firewall": fw_step},
        known_macs_hooks={"apply": lambda text: None, "firewall": lambda macs: loaded.append("loaded"),
                          "firewall_stale": stale})


def _journal(conn, event):
    return [r["detail"] for r in conn.execute("SELECT detail FROM journal WHERE event = ? ORDER BY id", (event,))]


def test_a_stale_firewall_is_rewritten_at_start_before_the_registered_list_loads(tmp_path, images_root):
    order: list[str] = []
    rt = _runtime(tmp_path, images_root, stale=lambda: "old conf",
                  fw_step=lambda nic: order.append("rewrite"), loaded=order)
    try:
        assert order == ["rewrite", "loaded"]
        assert _journal(rt.conn, "firewall_rewritten") == ["old conf"]
        assert _journal(rt.conn, "firewall_rewrite_failed") == []
    finally:
        rt.ctx.sender.stop()


def test_a_rewrite_that_failed_is_journaled_by_name_and_the_start_goes_on(tmp_path, images_root):
    """The upgrade script, not the server's start, is what turns this into a rollback (layer 3)."""
    order: list[str] = []
    rt = _runtime(tmp_path, images_root, stale=lambda: "old conf",
                  fw_step=lambda nic: "nft -c said no", loaded=order)
    try:
        assert _journal(rt.conn, "firewall_rewrite_failed") == ["old conf — nft -c said no"]
        assert _journal(rt.conn, "firewall_rewritten") == []
        assert order == ["loaded"]
    finally:
        rt.ctx.sender.stop()


def test_a_step_that_raises_is_a_failure_in_the_journal_not_a_crash(tmp_path, images_root):
    def boom(nic):
        raise RuntimeError("no nft binary")

    rt = _runtime(tmp_path, images_root, stale=lambda: "old conf", fw_step=boom, loaded=[])
    try:
        assert _journal(rt.conn, "firewall_rewrite_failed") == ["old conf — no nft binary"]
    finally:
        rt.ctx.sender.stop()


def test_a_current_firewall_is_not_touched_by_a_normal_start(tmp_path, images_root):
    steps: list[str] = []
    rt = _runtime(tmp_path, images_root, stale=lambda: None,
                  fw_step=lambda nic: steps.append("rewrite"), loaded=[])
    try:
        assert steps == []
        assert _journal(rt.conn, "firewall_rewritten") == [] == _journal(rt.conn, "firewall_rewrite_failed")
    finally:
        rt.ctx.sender.stop()


def test_both_events_have_a_hebrew_line_and_the_failure_is_an_error():
    from server.console import journal_he                                 # noqa: PLC0415

    for event in ("firewall_rewritten", "firewall_rewrite_failed"):
        assert journal_he.EVENTS_HE[event]
    assert "firewall_rewrite_failed" in journal_he._SEVERITY_ERR


# -- 3. tools/server-upgrade.sh ------------------------------------------------------------

pytestmark_upgrade = requires_native(("bash", BASH), why="server-upgrade.sh is bash")
TAG = "v0.53.0"


@pytest.fixture()
def bindir(tmp_path: Path) -> Path:
    path = tmp_path / "bin"
    path.mkdir()
    return path


def _nft_shim(bindir: Path, *, set_loaded: bool = True) -> None:
    """`nft list set inet imagesrv known_macs` answers 0 only when the live set exists."""
    fake_tool(bindir, "nft", "exit 0" if set_loaded else 'echo "Error: No such file or directory" >&2; exit 1')


def _upgrade(tmp_path: Path, bindir: Path, conf: Path | None):
    data, repo = _setup(tmp_path)
    _success_tools(bindir)
    (tmp_path / "units").mkdir(exist_ok=True)
    env = {**_upgrade_env(tmp_path, repo, data), "FAKE_TAG": TAG}
    if conf is not None:
        env["IMAGESRV_NFT_CONF"] = posix(conf)
    proc = run_bash(f'bash "{posix(repo / "tools" / "server-upgrade.sh")}" {TAG} "{posix(repo)}"',
                    tmp_path, bindir, env=env)
    return proc, _status(data), calls(tmp_path), (tmp_path / "upgrade.log").read_text(encoding="utf-8")


def _rolled_back(log: list[str]) -> bool:
    return any(" checkout --detach v0.48.0" in row for row in log)


@pytestmark_upgrade
def test_an_upgrade_whose_firewall_declares_the_set_and_has_it_loaded_succeeds(tmp_path, bindir):
    _nft_shim(bindir)
    proc, status, log, text = _upgrade(tmp_path, bindir, _conf(tmp_path, (FIXTURES / "primary.conf").read_text(encoding="utf-8")))
    assert proc.returncode == 0, text
    assert status["state"] == "done" and not _rolled_back(log)
    assert "nft list set inet imagesrv known_macs" in log


@pytest.mark.parametrize("conf_text", [LEGACY], ids=["conf-without-known_macs"])
@pytest.mark.parametrize("loaded", [True, False], ids=["live-set-present", "live-set-absent"])
@pytestmark_upgrade
def test_a_firewall_still_from_before_the_set_fails_the_upgrade_by_name(tmp_path, bindir, conf_text, loaded):
    """The conf says old -> rolled back, whatever the live ruleset says (a live set that a reboot loses is no evidence)."""
    _nft_shim(bindir, set_loaded=loaded)
    proc, status, log, _ = _upgrade(tmp_path, bindir, _conf(tmp_path, conf_text))
    assert proc.returncode != 0 and _rolled_back(log)
    assert status["state"] == "failed" and status["reason"] == "rollback"
    assert "known_macs" in status["error"] and "firewall_rewrite_failed" in status["error"]


@pytestmark_upgrade
def test_a_declared_set_that_is_not_loaded_in_the_live_firewall_fails_the_upgrade(tmp_path, bindir):
    _nft_shim(bindir, set_loaded=False)
    proc, status, log, _ = _upgrade(tmp_path, bindir, _conf(tmp_path, (FIXTURES / "primary.conf").read_text(encoding="utf-8")))
    assert proc.returncode != 0 and _rolled_back(log)
    assert status["state"] == "failed" and status["reason"] == "rollback" and "החיה" in status["error"]


@pytestmark_upgrade
def test_a_conf_that_cannot_be_read_fails_the_upgrade_instead_of_passing_it(tmp_path, bindir):
    """grep exits 2 on a directory: 'could not check' is not 'no ImageSrv firewall' (principle 5)."""
    _nft_shim(bindir)
    (tmp_path / "nftables.conf").mkdir()
    proc, status, log, _ = _upgrade(tmp_path, bindir, tmp_path / "nftables.conf")
    assert proc.returncode != 0 and _rolled_back(log)
    assert status["state"] == "failed" and "לא ניתן לקרוא" in status["error"]


@pytest.mark.parametrize("kind", ["no-file", "not-ours"])
@pytestmark_upgrade
def test_a_server_without_an_imagesrv_firewall_upgrades_and_nothing_is_enabled(tmp_path, bindir, kind):
    """#2440/#1074: `--no-firewall` (no file, or a file that is not ours) is said in the log, never a failure,
    and the upgrade does not call nft at all."""
    fake_tool(bindir, "nft", 'echo "nft must not run" >&2; exit 70')
    conf = tmp_path / "absent.conf" if kind == "no-file" else _conf(tmp_path, "table inet filter { }\n")
    proc, status, log, text = _upgrade(tmp_path, bindir, conf)
    assert proc.returncode == 0, text
    assert status["state"] == "done" and not any(row.startswith("nft ") for row in log)
    assert "אין חומת אש של ImageSrv" in text or "אינו של ImageSrv" in text


def test_a_conf_with_known_macs_but_without_the_feedback_port_is_stale_3512(tmp_path):
    """#3512: the range before the chunk engine's feedback port (portbase+3) joined it. A server upgraded from it
    keeps dropping the receivers' feedback until the rules are written again."""
    text = (FIXTURES / "primary.conf").read_text(encoding="utf-8")
    old = text.replace("udp dport 9000-9003", "udp dport 9000-9001")        # פורט-הפצה-מכוון: the old installed range
    assert old != text and deploy_net.KNOWN_MACS_DECL in old
    reason = deploy_net.stale_firewall(_conf(tmp_path, old))
    assert reason and "portbase+3" in reason
