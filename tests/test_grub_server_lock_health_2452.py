"""#2452: the health page says whether the server's OWN GRUB menu is locked.

A server updated from the console button from a version before #2450 stayed open (``grub>`` with
no password) and said nothing: the first update ran the *installed* version's script, which does not
call ``deploy/grub-lock-host.sh``, and no ``grub_server_lock_failed`` was written (VM, 21/11). The
existing ``grub_password`` row (#2454) is a different thing -- a reminder to keep the password off
the server -- and is yellow on a locked server and on an open one alike.

The new row ``grub_server_lock`` reads ``/boot/grub/grub.cfg`` back and has three separate answers
(principle 5): ``ok`` (locked: ``set superusers`` and a ``password_pbkdf2`` before the first entry),
``bad`` (read, and not locked), ``unknown`` (the file could not be read, or is not a menu at all).
"Could not read" is never "locked" and never "open".
"""

from __future__ import annotations

from pathlib import Path

import pytest

from server.system import grub_lock_state

HASH = "grub.pbkdf2.sha512.100000." + "AB" * 16 + "." + "CD" * 16

HEADER = """\
#
# DO NOT EDIT THIS FILE
#
### BEGIN /etc/grub.d/00_header ###
menuentry_id_option="--id"
export menuentry_id_option
set default="0"
### END /etc/grub.d/00_header ###
"""

LOCK = f"""\
### BEGIN /etc/grub.d/01_imagesrv_lock ###
set superusers="imagesrv"
password_pbkdf2 imagesrv {HASH}
menuentry_id_option="--unrestricted $menuentry_id_option"
export menuentry_id_option
### END /etc/grub.d/01_imagesrv_lock ###
"""

ENTRIES = """\
### BEGIN /etc/grub.d/10_linux ###
menuentry 'Debian GNU/Linux' $menuentry_id_option 'gnulinux-simple-x' {
\tlinux /vmlinuz root=/dev/sda2 ro quiet
}
submenu 'Advanced options for Debian GNU/Linux' $menuentry_id_option 'gnulinux-advanced-x' {
\tmenuentry 'Debian GNU/Linux, with Linux 6.12' $menuentry_id_option 'gnulinux-6.12' {
\t\tlinux /vmlinuz-6.12 root=/dev/sda2 ro
\t}
}
### END /etc/grub.d/10_linux ###
"""


def _write(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "grub.cfg"
    path.write_text(text, encoding="utf-8")
    return path


def test_a_locked_menu_is_ok(tmp_path):
    state, detail = grub_lock_state.lock_status(_write(tmp_path, HEADER + LOCK + ENTRIES))
    assert state == "ok", detail
    assert "נעול" in detail


def test_an_open_menu_is_bad_and_says_what_is_missing(tmp_path):
    """The server the 21/11 update left behind: entries, no lock lines at all."""
    state, detail = grub_lock_state.lock_status(_write(tmp_path, HEADER + ENTRIES))
    assert state == "bad", detail
    assert "set superusers" in detail and "password_pbkdf2" in detail
    assert "פתוח" in detail


def test_superusers_without_a_password_is_not_the_lock_2450_means(tmp_path):
    lock = LOCK.replace(f"password_pbkdf2 imagesrv {HASH}\n", "")
    state, detail = grub_lock_state.lock_status(_write(tmp_path, HEADER + lock + ENTRIES))
    assert state == "bad", detail
    assert "password_pbkdf2" in detail and "set superusers" not in detail


def test_a_password_hash_grub_would_not_take_is_not_a_lock(tmp_path):
    lock = LOCK.replace(HASH, "not-a-hash")
    state, detail = grub_lock_state.lock_status(_write(tmp_path, HEADER + lock + ENTRIES))
    assert state == "bad", detail


def test_lock_lines_after_the_first_entry_do_not_count(tmp_path):
    """GRUB reads superusers/password before the entries; a line inside an entry is not the lock."""
    inside = ENTRIES.replace("\tlinux /vmlinuz root=/dev/sda2 ro quiet\n",
                             f'set superusers="imagesrv"\npassword_pbkdf2 imagesrv {HASH}\n')
    state, detail = grub_lock_state.lock_status(_write(tmp_path, HEADER + inside))
    assert state == "bad", detail


def test_a_file_that_cannot_be_read_is_unknown_not_locked_and_not_open(tmp_path, caplog):
    missing = grub_lock_state.lock_status(tmp_path / "nope" / "grub.cfg")
    folder = grub_lock_state.lock_status(tmp_path)                 # a directory: read_bytes raises OSError
    for state, detail in (missing, folder):
        assert state == "unknown", detail
        assert "לא נבדק" in detail
    assert any("grub.cfg" in r.getMessage() or str(tmp_path) in r.getMessage() for r in caplog.records)


def test_a_file_that_is_not_a_menu_is_unknown(tmp_path):
    """Empty, or text with no entry at all: nothing proves this is the menu GRUB reads."""
    for text in ("", "# nothing here\nset default=0\n", HEADER + LOCK):
        state, detail = grub_lock_state.lock_status(_write(tmp_path, text))
        assert state == "unknown", (text, detail)


def test_the_three_answers_are_three_different_states(tmp_path):
    answers = {
        grub_lock_state.lock_status(_write(tmp_path, HEADER + LOCK + ENTRIES))[0],
        grub_lock_state.lock_status(_write(tmp_path, HEADER + ENTRIES))[0],
        grub_lock_state.lock_status(tmp_path / "missing.cfg")[0],
    }
    assert answers == {"ok", "bad", "unknown"}


# --- the console: the row is on /api/console/health -------------------------------------------------


def _console(tmp_path: Path, images_root, password_file, **hooks):
    pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from conftest import complete_console_login
    from server.app import create_app
    from server.console import users

    app = create_app(tmp_path / "data", images_root, "http://10.44.12.10:7712",
                     health_hooks={"interfaces": lambda: [], **hooks}, grub_password_file=password_file)
    users.create(app.state.ctx.conn, "noc", "admin-pass-123", "admin", by="test", check_policy=False)
    admin = TestClient(app)
    complete_console_login(admin, app.state.ctx.conn, "noc", "admin-pass-123")
    return admin


def _row(admin) -> dict | None:
    r = admin.get("/api/console/health")
    assert r.status_code == 200, r.text
    rows = [c for c in r.json() if c["id"] == "grub_server_lock"]
    assert len(rows) <= 1, rows
    return rows[0] if rows else None


def test_a_real_server_gets_the_row_and_it_follows_the_file(tmp_path, images_root, monkeypatch):
    cfg = tmp_path / "boot" / "grub.cfg"
    cfg.parent.mkdir()
    monkeypatch.setattr(grub_lock_state, "GRUB_CFG", cfg)
    admin = _console(tmp_path, images_root, tmp_path / "etc" / "grub-password")

    assert _row(admin)["state"] == "unknown"                       # not read yet: not "locked", not "open"
    cfg.write_text(HEADER + ENTRIES, encoding="utf-8")
    row = _row(admin)
    assert row["state"] == "bad" and row["label"] == "נעילת GRUB של השרת", row
    cfg.write_text(HEADER + LOCK + ENTRIES, encoding="utf-8")
    assert _row(admin)["state"] == "ok"


def test_the_row_is_not_the_password_reminder(tmp_path, images_root, monkeypatch):
    """#2454's row stays a separate row with its own state."""
    cfg = tmp_path / "grub.cfg"
    cfg.write_text(HEADER + LOCK + ENTRIES, encoding="utf-8")
    monkeypatch.setattr(grub_lock_state, "GRUB_CFG", cfg)
    admin = _console(tmp_path, images_root, tmp_path / "etc" / "grub-password")
    rows = {c["id"]: c["state"] for c in admin.get("/api/console/health").json()}
    assert rows["grub_server_lock"] == "ok" and rows["grub_password"] == "warn", rows


def test_a_development_station_has_no_row(tmp_path, images_root, monkeypatch):
    """No password file (tests, Windows): no GRUB of its own to speak about -- no row, not a green one."""
    cfg = tmp_path / "grub.cfg"
    cfg.write_text(HEADER + ENTRIES, encoding="utf-8")
    monkeypatch.setattr(grub_lock_state, "GRUB_CFG", cfg)
    assert _row(_console(tmp_path, images_root, None)) is None


def test_an_injected_hook_wins_over_the_default(tmp_path, images_root):
    admin = _console(tmp_path, images_root, tmp_path / "etc" / "grub-password",
                     grub_server_lock=lambda: ("warn", "injected"))
    assert _row(admin) == {"id": "grub_server_lock", "label": "נעילת GRUB של השרת", "state": "warn",
                           "detail": "injected"}
